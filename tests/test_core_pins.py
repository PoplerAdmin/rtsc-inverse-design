"""Frozen certified core (architecture §1.1).

Every file of ``src/rtt/core`` and of its test suite ``tests/core`` must match the sha256 recorded
in ``src/rtt/core/PINS.json``. The core holds the certified Eliashberg engine and the policy that
turns spectra into verdicts; its soundness arguments (``core/certify/PROOFS.md``, the Lean
proofs) are about these exact bytes, so a silent edit would invalidate them. A deliberate change
re-derives the affected arguments and then rewrites the pins::

    python tests/test_core_pins.py --update
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "src" / "rtt" / "core"
TCORE = ROOT / "tests" / "core"
PINS_PATH = CORE / "PINS.json"
SKIP_PARTS = {"__pycache__"}
SKIP_NAMES = {"PINS.json", "crosstest_table.json", "crosstest_table.md"}   # regenerated by the oracle test


def _files(root: Path) -> list[str]:
    return sorted(p.relative_to(root).as_posix() for p in root.rglob("*")
                  if p.is_file() and not SKIP_PARTS & set(p.parts) and p.name not in SKIP_NAMES
                  and p.suffix != ".pyc")


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def current() -> dict:
    return {"package": {r: sha(CORE / r) for r in _files(CORE)},
            "tests": {r: sha(TCORE / r) for r in _files(TCORE)}}


PINS = json.loads(PINS_PATH.read_text(encoding="utf-8"))


@pytest.mark.parametrize("rel", sorted(PINS["package"]))
def test_core_file_pinned(rel):
    assert sha(CORE / rel) == PINS["package"][rel], f"src/rtt/core/{rel} changed (see module docstring)"


@pytest.mark.parametrize("rel", sorted(PINS["tests"]))
def test_core_test_file_pinned(rel):
    assert sha(TCORE / rel) == PINS["tests"][rel], f"tests/core/{rel} changed"


def test_no_unpinned_core_files():
    cur = current()
    assert set(cur["package"]) == set(PINS["package"]) and set(cur["tests"]) == set(PINS["tests"])


if __name__ == "__main__" and "--update" in sys.argv:
    PINS_PATH.write_text(json.dumps(current(), indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {PINS_PATH}")
