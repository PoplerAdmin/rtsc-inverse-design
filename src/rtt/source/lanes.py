"""Generation lanes G1-G5 (architecture §3.3; doc 02 §5(d)) and the daily plan.

Every lane uses one *shipped* MatterGen checkpoint and conditions on exactly that checkpoint's
own property set (``CHECKPOINT_PROPERTIES``; R12 #9). :class:`LaneSpec` refuses anything
else at construction time. The planned A-adapter lane ``GA`` is refused unless
``allow_adapter=True`` and a ``model_path`` is given (it is not a shipped checkpoint).

=====  =====  =========================================  =================================================
lane   share  checkpoint                                 conditioning (one value per job)
=====  =====  =========================================  =================================================
G1     0.55   chemical_system_energy_above_hull          {chemical_system: X-Y-H, energy_above_hull: U(0,0.3)}
G2     0.15   space_group                                {space_group: one of S6 list}
G3     0.10   dft_band_gap / dft_mag_density             {dft_band_gap: 0.0} / {dft_mag_density: 0.0}
G4     0.15   chemical_system / ml_bulk_modulus          non-hydride systems (doc 02 5(c)) / {ml_bulk_modulus: high}
G5     0.05   mattergen_base                             none (bias control)
=====  =====  =========================================  =================================================
"""
