class UnsupportedConditioningError(ValueError):
    pass


def norm_chemsys(cs: str | Sequence[str]) -> str:
    els = cs.split("-") if isinstance(cs, str) else list(cs)
    return "-".join(sorted({e.strip() for e in els if e.strip()}))


@dataclass(frozen=True)
class LaneSpec:
    lane: str
    checkpoint: str | None                     # shipped pretrained name
    conditioning: Mapping[str, Any] = field(default_factory=dict)
    guidance: float = 2.0                      # gamma; ignored (0) when unconditioned
    batch_size: int = 64
    model_path: str | None = None              # GA only
    allow_adapter: bool = False
    source_id: str = "doc12#3.3"

    def __post_init__(self):
        if self.lane not in GENERATION_LANES:
            raise UnsupportedConditioningError(f"unknown generation lane {self.lane!r}")
        cond = dict(self.conditioning)
        if self.lane == "GA" or self.model_path is not None:
            if not (self.allow_adapter and self.model_path and self.lane == "GA"):
                raise UnsupportedConditioningError(
                    "fine-tuned adapters (lane GA) are not shipped checkpoints; set lane='GA', "
                    "model_path and allow_adapter=True explicitly once the adapter is accepted")
            return
        if self.checkpoint not in CHECKPOINT_PROPERTIES:
            raise UnsupportedConditioningError(f"{self.checkpoint!r} is not a shipped MatterGen checkpoint")
        props = CHECKPOINT_PROPERTIES[self.checkpoint]
        if set(cond) != set(props):
            raise UnsupportedConditioningError(
                f"checkpoint {self.checkpoint!r} conditions on exactly {sorted(props) or 'nothing'}; "
                f"got {sorted(cond)} (only a checkpoint's own property set is allowed, R12 #9)")
        if "chemical_system" in cond:
            els = cond["chemical_system"].split("-")
            bad = sorted(set(els) - MATTERGEN_ELEMENTS)
            if bad:
                raise UnsupportedConditioningError(f"MatterGen cannot generate {bad}")
            if cond["chemical_system"] != norm_chemsys(els):
                raise UnsupportedConditioningError("chemical_system must be sorted 'A-B-C'")
        if "space_group" in cond and not (isinstance(cond["space_group"], int) and 1 <= cond["space_group"] <= 230):
            raise UnsupportedConditioningError(f"space_group {cond['space_group']!r} not an int in 1..230")
        for k in ("energy_above_hull", "dft_band_gap", "dft_mag_density", "ml_bulk_modulus"):
            if k in cond and not isinstance(cond[k], (int, float)):
                raise UnsupportedConditioningError(f"{k} must be a number")

    @property
    def conditioned(self) -> bool:
        return bool(self.conditioning) or self.lane == "GA"

    @property
    def effective_guidance(self) -> float:
        return float(self.guidance) if self.conditioned else 0.0

    @property
    def s_per_structure(self) -> float:
        return S_PER_STRUCT["conditional" if self.conditioned else "unconditional"]

    def to_json(self) -> dict:
        return {"lane": self.lane, "checkpoint": self.checkpoint, "conditioning": dict(self.conditioning),
                "guidance": self.effective_guidance, "batch_size": self.batch_size,
                "model_path": self.model_path, "source_id": self.source_id}


@dataclass(frozen=True)
class LaneJob:
    spec: LaneSpec
    n: int
    seed: int
    batch_id: str

    @property
    def gpu_s_est(self) -> float:
        return self.n * self.spec.s_per_structure


# ----------------------------------------------------------------------------- chemsys lists
def _chemsys_path(targets: Any) -> tuple[Path | None, str | None]:
    path = None
    if targets is not None:
        try:
            path = targets.get("chemsys.list", None)
        except Exception:  # noqa: BLE001
            path = None
    if not path:
        return None, None
    p = Path(path)
    if not p.is_absolute():
        from ..config import CONFIG_DIR, REPO_ROOT
        for base in (CONFIG_DIR, REPO_ROOT, Path(getattr(targets, "path", ".")).parent):
            if (base / p).exists():
                return base / p, str(path)
    return (p if p.exists() else None), str(path)


def read_chemsys_sections(p: Path) -> dict[str, list[str]]:
    """Sections of a chemsys list file: ``[name]`` headers, one system per line, '#' comments.
    Lines before any header belong to section ``family1`` (older one-section files)."""
    sec = "family1"
    out: dict[str, list[str]] = {}
    for line in Path(p).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            sec = line[1:-1].strip()
            out.setdefault(sec, [])
            continue
        out.setdefault(sec, []).append(norm_chemsys(line))
    return out


def load_chemsys_list(targets: Any = None, section: str = "hydride") -> tuple[list[str], list[str]]:
    """(systems, flags). Reads ``targets.toml [chemsys] list`` (configs/targets/chemsys_list.txt,
    generated from doc 02 by :func:`write_chemsys_list`). ``section='hydride'`` returns every
    section except ``nonhydride`` (the G1 X-Y-H systems); ``section='nonhydride'`` the 5(c)
    systems for G4.

    B11 (doc 31 §3): a missing or empty file is no longer silent. The fallback is the doc 02
    family-1 / 5(c) enumeration in code, a WARNING is logged and the flag
    ``DEFAULT_CHEMSYS_FALLBACK(<why>)`` is returned (plan_day writes it into every lane job's
    source id, so it reaches each candidate's origin)."""
    import logging
    p, declared = _chemsys_path(targets)
    if p is not None:
        secs = read_chemsys_sections(p)
        if section == "nonhydride":
            out = list(secs.get("nonhydride", []))
        else:
            out = [c for k, v in secs.items() if k != "nonhydride" for c in v]
        ok = [c for c in out if set(c.split("-")) <= MATTERGEN_ELEMENTS]
        if ok:
            from ..config import sha256_of
            flags = [f"CHEMSYS_FILE(sha256={sha256_of(p)[:12]})"]
            if len(ok) != len(out):
                flags.append("CHEMSYS_OUT_OF_DOMAIN_DROPPED")
            return sorted(dict.fromkeys(ok)), flags
        why = f"no {section} systems in {declared}"
    else:
        why = "targets.toml [chemsys] list not set" if declared is None else f"{declared} not found"
    logging.getLogger("rtt.source.lanes").warning(
        "chemsys list fallback (%s): using the in-code doc 02 %s enumeration", why,
        "5(c)" if section == "nonhydride" else "family-1")
    fb = list(PROFILE_NONHYDRIDE) if section == "nonhydride" else default_chemsys_list()
    return [norm_chemsys(c) for c in fb], [f"DEFAULT_CHEMSYS_FALLBACK({why})"]


def default_chemsys_list() -> list[str]:
    """Doc 02 S10 / priority family 1: donor x late-TM x H (no donor-donor-H systems, B11)."""
    out = [norm_chemsys([d, t, "H"]) for d in DEFAULT_DONORS for t in DEFAULT_TMS]
    return sorted(dict.fromkeys(out))


def write_chemsys_list(path: str | Path) -> Path:
    """Write the chemsys list file from the doc 02 profile (family 1 + non-hydride channel)."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# {ln}" if ln else "#" for ln in CHEMSYS_SOURCE_NOTE.splitlines()]
    lines += ["", "[family1]"] + default_chemsys_list()
    lines += ["", "[nonhydride]"] + sorted(norm_chemsys(c) for c in PROFILE_NONHYDRIDE)
    p.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return p


# ----------------------------------------------------------------------------- plan
def _weighted_cycle(items: Sequence[str], weights: Mapping[str, float] | None, k: int,
                    rng: random.Random, floor: float = 0.2) -> list[str]:
    """k draws, weighted (each weight floored at ``floor`` x mean so no system starves; §3.3)."""
    if not items:
        return []
    w = [max(float((weights or {}).get(x, 1.0)), 0.0) for x in items]
    mean = sum(w) / len(w) if sum(w) > 0 else 1.0
    w = [max(x, floor * mean) for x in w]
    return rng.choices(list(items), weights=w, k=k)


def _get(cfg: Any, key: str, default: Any) -> Any:
    if cfg is None:
        return default
    try:
        return cfg.get(key, default)
    except TypeError:
        return default


def plan_day(machine: Any, targets: Any, weights: Mapping[str, float] | None = None, *,
             tiers: Any = None, day: str = "day0", seed: int = 0, gpu_h: float | None = None,
             batch_size: int | None = None) -> list[LaneJob]:
    """Split one day's MatterGen GPU budget over the lanes.

    * GPU hours: ``gpu_h`` or ``machine [lanes.G] mattergen_gpu_h`` (default 15 h, §8.2).
    * Shares: ``tiers [S1] lane_shares`` or :data:`DEFAULT_SHARES`.
    * ``weights``: G1 chemical-system weights from the S4/S5 feedback (§3.3); floor 0.2.
    * One job = one conditioning value = ``batch_size`` structures (default 64, doc 10 §3.2).
    """
    gpu_h = float(gpu_h if gpu_h is not None else _get(machine, "lanes.G.mattergen_gpu_h", 15.0))
    bs = int(batch_size or _get(machine, "lanes.G.mattergen_batch", 64))
    shares = dict(_get(tiers, "S1.lane_shares", None) or DEFAULT_SHARES)
    rng = random.Random(int(hashlib.sha256(f"{day}|{seed}".encode()).hexdigest()[:8], 16))
    hyd, hflags = load_chemsys_list(targets)
    g1_src = "doc02#5d1|" + ",".join(hflags) if hflags else "doc02#5d1"
    sgs = list(_get(targets, "soft.S6_space_groups", None) or SPACE_GROUPS_S6)
    jobs: list[LaneJob] = []
    tot = sum(shares.values())

    def n_jobs(lane: str, s_per: float) -> int:
        sec = gpu_h * 3600 * shares.get(lane, 0.0) / tot
        return int(sec // (bs * s_per))

    def add(spec: LaneSpec, k: int) -> None:
        jobs.append(LaneJob(spec=spec, n=bs, seed=rng.randrange(1, 2**31 - 1),
                            batch_id=f"{day}-{spec.lane}-{k:03d}"))

    for k, cs in enumerate(_weighted_cycle(hyd, weights, n_jobs("G1", S_PER_STRUCT["conditional"]), rng)):
        eh = round(rng.uniform(*EHULL_COND_RANGE), 3)
        add(LaneSpec("G1", "chemical_system_energy_above_hull",
                     {"chemical_system": cs, "energy_above_hull": eh}, batch_size=bs,
                     source_id=g1_src), k)
    for k in range(n_jobs("G2", S_PER_STRUCT["conditional"])):
        add(LaneSpec("G2", "space_group", {"space_group": int(sgs[k % len(sgs)])}, batch_size=bs,
                     source_id="doc02#5d2"), k)
    for k in range(n_jobs("G3", S_PER_STRUCT["conditional"])):
        if k % 2 == 0:
            add(LaneSpec("G3", "dft_band_gap", {"dft_band_gap": 0.0}, batch_size=bs, source_id="doc02#5d3:H1"), k)
        else:
            add(LaneSpec("G3", "dft_mag_density", {"dft_mag_density": 0.0}, batch_size=bs,
                         source_id="doc02#5d3:H2"), k)
    nh_cfg = _get(targets, "chemsys.nonhydride", None)
    if nh_cfg:
        nh, g4_src = list(nh_cfg), "doc02#5c|targets.toml chemsys.nonhydride"
    else:
        nh, nflags = load_chemsys_list(targets, section="nonhydride")
        g4_src = "doc02#5c|" + ",".join(nflags) if nflags else "doc02#5c"
    for k in range(n_jobs("G4", S_PER_STRUCT["conditional"])):
        if k % 4 == 3:
            add(LaneSpec("G4", "ml_bulk_modulus", {"ml_bulk_modulus": ML_BULK_MODULUS_HIGH_GPA}, batch_size=bs,
                         source_id="doc02#5c:S9"), k)
        else:
            add(LaneSpec("G4", "chemical_system", {"chemical_system": norm_chemsys(nh[k % len(nh)])},
                         batch_size=bs, source_id=g4_src), k)
    for k in range(n_jobs("G5", S_PER_STRUCT["unconditional"])):
        add(LaneSpec("G5", "mattergen_base", {}, batch_size=bs, source_id="doc02#5d5"), k)
    return jobs


def plan_summary(jobs: Sequence[LaneJob]) -> dict:
    out: dict[str, dict] = {}
    for j in jobs:
        d = out.setdefault(j.spec.lane, {"jobs": 0, "structures": 0, "gpu_h_est": 0.0})
        d["jobs"] += 1
        d["structures"] += j.n
        d["gpu_h_est"] = round(d["gpu_h_est"] + j.gpu_s_est / 3600, 3)
    return out


